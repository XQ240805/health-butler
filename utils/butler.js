let lastRule = null; // 当前话题，用来接住后续的补充
let followUsed = {}; // 每个话题已经用到第几条深入建议
let fallbackCount = 0;

function formatRule(rule) {
  const tips = rule.tips.map((x, i) => `${i + 1}. ${x}`).join('\n');
  return `${rule.feel}\n\n可以试试这几件事：\n${tips}\n\n${rule.see}`;
}

function followUp(rule) {
  const f = FOLLOW[rule.name];
  if (!f) return null;
  const used = followUsed[rule.name] || 0;
  const tip = f.tips[Math.min(used, f.tips.length - 1)];
  followUsed[rule.name] = used + 1;
  return tip;
}

function reply(text) {
  const t = (text || '').trim();
  if (!t) return '我在。你可以说说最近身体或者作息上哪里不太舒服。';

  if (EMERGENCY.some((w) => t.indexOf(w) >= 0)) {
    return '你描述的情况需要当面评估，不要等。请立刻拨打 120，或让身边的人送你去最近医院的急诊。\n\n在等待的过程中保持安静坐卧，松开衣领，不要自行服药。这条消息我无法替代医生的判断。';
  }

  if (/^(你好|您好|hi|hello|在吗|嗨)/i.test(t)) {
    return '在的。我是你的健康管家，可以陪你梳理作息、饮食、睡眠和一些常见的不适。\n\n你今天想先聊哪一块？也可以直接说说最近哪里不太舒服。';
  }

  if (/(谢谢|感谢|辛苦)/.test(t)) {
    return '不客气。记录下来比记住更重要，有变化随时和我说。';
  }

  const rule = pick(t);
  if (rule) {
    lastRule = rule;
    followUsed[rule.name] = 0;
    return formatRule(rule);
  }

  // 没有命中关键词，但刚才在聊某个话题：顺着往下接，不重复提问
  if (lastRule) {
    const tip = followUp(lastRule);
    const f = FOLLOW[lastRule.name];
    if (tip) {
      const ack = t.length <= 12 ? '嗯。' : '明白。';
      const ask = f && t.length <= 12 ? `\n\n${f.ask}` : '';
      return `${ack}${tip}${ask}`;
    }
  }

  const fb = FALLBACKS[fallbackCount % FALLBACKS.length];
  fallbackCount += 1;
  return fb;
}

